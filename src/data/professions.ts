export function buildInitialLiabilities(prof: Profession): LiabilityItem[] {
  const list: LiabilityItem[] = [];
  if (prof.housingDebt > 0) {
    list.push({
      id: 'housing',
      name: prof.housingLabel,
      balance: prof.housingDebt,
      monthlyPayment: prof.housingExpense,
      canPayPartially: true,
    });
  }
  if (prof.autoDebt > 0) {
    list.push({
      id: 'auto',
      name: 'Автонесие / Көлік бөліп төлеу',
      balance: prof.autoDebt,
      monthlyPayment: prof.autoExpense,
      canPayPartially: true,
    });
  }
  if (prof.kaspiRedDebt > 0) {
    list.push({
      id: 'kaspi_red',
      name: 'Kaspi Red / Бөліп төлеу',
      balance: prof.kaspiRedDebt,
      monthlyPayment: prof.kaspiRedExpense,
      canPayPartially: false,
    });
  }
  if (prof.otherLoanDebt > 0) {
    list.push({
      id: 'other_loan',
      name: prof.otherLoanLabel || 'Тұтынушылық несие',
      balance: prof.otherLoanDebt,
      monthlyPayment: prof.otherLoanExpense,
      canPayPartially: false,
    });
  }
  return list;
}
